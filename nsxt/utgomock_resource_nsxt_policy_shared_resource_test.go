func TestUnitNsxt_resourceNsxtPolicySharedResourceImporter(t *testing.T) {
	res := resourceNsxtPolicySharedResource()

	t.Run("valid path sets share_path", func(t *testing.T) {
		d := schema.TestResourceDataRaw(t, res.Schema, map[string]interface{}{})
		d.SetId(sharedResPath)

		out, err := resourceNsxtPolicySharedResourceImporter(d, newGoMockProviderClient())
		require.NoError(t, err)
		require.Len(t, out, 1)
		assert.Equal(t, sharedResID, d.Id())
		assert.Equal(t, sharedResSharePath, d.Get("share_path"))
	})

	t.Run("non-policy-path id fails", func(t *testing.T) {
		d := schema.TestResourceDataRaw(t, res.Schema, map[string]interface{}{})
		d.SetId("plain-id")

		_, err := resourceNsxtPolicySharedResourceImporter(d, newGoMockProviderClient())
		require.Error(t, err)
	})

	t.Run("Import and Read populate permission", func(t *testing.T) {
		ctrl := gomock.NewController(t)
		mockSDK, restore := setupSharedResMock(t, ctrl)
		t.Cleanup(restore)
		permission := "ASSOCIATION_ONLY"
		response := sharedResAPIResponse()
		response.WithPermission = &permission
		mockSDK.EXPECT().Get(sharedResShareID, sharedResID).Return(response, nil)
		d := schema.TestResourceDataRaw(t, res.Schema, map[string]interface{}{})
		d.SetId(sharedResPath)

		_, err := resourceNsxtPolicySharedResourceImporter(d, newGoMockProviderClient())
		require.NoError(t, err)
		require.NoError(t, resourceNsxtPolicySharedResourceRead(d, newGoMockProviderClient()))
		assert.Equal(t, permission, d.Get("with_permission"))
	})
}
